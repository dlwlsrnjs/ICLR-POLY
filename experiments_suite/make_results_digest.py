#!/usr/bin/env python3
"""Compile the current experiment state into one readable digest: experiments_suite/RESULTS_DIGEST.md.
Reads only stored aggregates (no GPU). Safe to re-run any time (the merge watcher does)."""
import json, glob, os, collections
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "exp02_panel_collect" / "results"
E5 = HERE / "exp05_willingness_probe" / "results"


def load(p):
    try: return json.load(open(p))
    except Exception: return None


def panel_coverage():
    atk = collections.Counter()
    for p in glob.glob(str(R / "attack" / "*.json")):
        b = os.path.basename(p)[:-5]
        if "__" in b: atk[b.split("__", 1)[0]] += 1
    benign = {os.path.basename(p)[:-5] for p in glob.glob(str(R / "benign" / "*.json"))}
    tags = sorted(set(atk) | benign)
    return atk, benign, tags


def main():
    out = []
    w = out.append
    w("# Results digest — current state\n")
    w("Auto-generated by `make_results_digest.py` from stored aggregates. Harmful raw stays in the "
      "bucket. Numbers over the models collected so far; L40S big-model harmful matrices fill in later.\n")

    atk, benign, tags = panel_coverage()
    w("## 1. Panel coverage (harmful arms / benign prior)\n")
    w("| model_ds | arms | benign |\n|---|---|---|")
    for t in tags:
        w(f"| {t} | {atk.get(t,0)} | {'Y' if t in benign else '-'} |")
    w("")

    d = load(R / "space_ab_compare.json")
    if d:
        w("## 2. Arm-space A/B/C/D (per model×dataset; oracle / benign-only / adaptive@8)\n")
        w("| tag | held | space | n | oracle | benign_only | adaptive@8 |\n|---|---|---|---|---|---|---|")
        for rec in d:
            for s, v in rec.items():
                if isinstance(v, dict) and "oracle" in v:
                    w(f"| {rec['tag']} | {rec.get('held','')} | {s} | {v['n_arms']} | "
                      f"{v['oracle']} | {v['benign_only']} | {v['adaptive8']} |")
        w("")

    d = load(R / "strategy_bakeoff.json")
    if d:
        w("## 3. Selector strategy bake-off (which GP variant wins)\n")
        w(f"- cells compared: {d.get('n_cells')}")
        w(f"- AUC wins: {d.get('wins_auc')}")
        w(f"- mean rank (AUC, lower=better): {d.get('mean_rank_auc')}\n")

    dm, dl = load(R / "adaptive_subspace_mj.json"), load(R / "adaptive_subspace_lg.json")
    if dm or dl:
        w("## 4. Adaptive subspace pruning (final active axes per cell)\n")
        for name, dd in (("mj", dm), ("lg", dl)):
            if not isinstance(dd, dict): continue
            for tag, v in dd.items():
                axes = v.get("final_active_axes") if isinstance(v, dict) else None
                if axes: w(f"- {tag}: active axes = {axes}")
        w("")

    d = load(R / "axis_drop_ablation.json")
    if d:
        w("## 5. Axis-drop ablation\n")
        w(f"- mean drop effect (ucb_pibo): {d.get('mean_drop_effect_ucb_pibo')}  "
          f"(cells helped {d.get('cells_helped')}/{d.get('n_cells')})\n")

    d = load(E5 / "transfer_validation.json")
    if d:
        s = d.get("summary", {})
        w("## 6. Willingness transfer (benign FalseReject -> harmful comply)\n")
        for ch, v in s.get("by_channel", {}).items():
            w(f"- {ch}: argmax_agreement={v['argmax_agreement']} mean_pearson={v['mean_pearson']} (n={v['n']})")
        fs = s.get("benign_feature_vs_harmful_unsafe_pooled_pearson")
        if fs: w(f"- benign feature → harmful unsafe (pooled pearson): {fs}")
        w("- **Honest read:** benign nonrefusal does NOT predict harmful comply (see "
          "exp05/TRANSFER_FINDING.md). Comprehension transfers; willingness needs a small harmful "
          "confirmation on the target.\n")

    fp = sorted(glob.glob(str(E5 / "willingness_prior_falsereject_*.json")))
    if fp:
        w("## 7. Willingness fingerprints (FalseReject)\n")
        w(f"- {len(fp)} models have a FalseReject willingness prior; see "
          "exp05/results/willingness_fingerprint_summary.md for the per-frame table.\n")

    big = ["falcon3_7b", "gemma2_2b_it", "gemma2_9b_it", "llama31_8b_it", "qwen25_14b", "mistral24b"]
    pend = [t for t in big if atk.get(t + "_mj", 0) == 0 or atk.get(t + "_lg", 0) == 0]
    w("## 8. Pending\n")
    w(f"- L40S harmful full-matrix for: {', '.join(pend) if pend else 'none — all big models collected'}")
    w("- On arrival the merge watcher rebuilds manifest + tables + transfer_validation (n→~9).\n")

    (HERE / "RESULTS_DIGEST.md").write_text("\n".join(out))
    print(f"WROTE {HERE/'RESULTS_DIGEST.md'} ({len(tags)} model-datasets, {len(fp)} willingness priors)")


if __name__ == "__main__":
    main()
